/** 点赞 Top20 + 浏览 Top20 合并去重（同 dedupeKey 保留更高互动） */
export function dedupeHotPool(items: HotItem[]): HotItem[] {
  const byKey = new Map<string, HotItem>()
  for (const item of items) {
    const prev = byKey.get(item.dedupeKey)
    if (!prev) {
      byKey.set(item.dedupeKey, item)
      continue
    }
    const score = item.likes + item.views
    const prevScore = prev.likes + prev.views
    if (score > prevScore) byKey.set(item.dedupeKey, item)
  }
  return [...byKey.values()].sort((a, b) => b.likes + b.views - (a.likes + a.views))
}

export function topByLikes(items: HotItem[], n = 20) {
  return [...items].sort((a, b) => b.likes - a.likes).slice(0, n)
}

export function topByViews(items: HotItem[], n = 20) {
  return [...items].sort((a, b) => b.views - a.views).slice(0, n)
}
